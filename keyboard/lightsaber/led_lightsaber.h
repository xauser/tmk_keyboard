#ifndef LED_LIGTHSABER_H 
#define LED_LIGTHSABER_H

enum backlight_level {
    BACKLIGHT_LEVEL_ALPHA   = 0b0000001,
    BACKLIGHT_LEVEL_PCB     = 0b0000010,
    BACKLIGHT_LEVEL_NUMERIC = 0b0000100,
    BACKLIGHT_LEVEL_FROW    = 0b0001000,
    BACKLIGHT_LEVEL_TOPRGHT = 0b0010000,
    BACKLIGHT_LEVEL_MODNUM  = 0b0100000,
    BACKLIGHT_LEVEL_ALL     = 0b0111111,
    BACKLIGHT_LEVEL_SWITCH  = 0b0111101
};

void led_init(void);
void backlight_set(uint8_t level);

#endif // LED_LIGTHSABER_H
